#!/usr/bin/env python3
"""
FastAPI wrapper around pipeline.py.

Endpoints:
  POST /jobs/preflight    reserve queue/disk capacity before sending a video
  POST /jobs              upload a video + metadata -> enqueue a reserved job
  GET  /jobs              list jobs owned by the current browser session
  GET  /jobs/{id}         poll one owned job's status/progress
  GET  /jobs/{id}/file    download/preview the finished MP4
  POST /jobs/{id}/drive   save the finished MP4 into Google Drive
  DELETE /jobs/{id}       remove an owned finished/failed job
  GET  /healthz           Railway liveness/configuration check

Video uploads are streamed to disk and jobs run through a bounded worker
pool. Browser sessions are isolated with an opaque X-Session-Id generated by
the frontend. This is lightweight internal-team isolation, not a substitute
for full user authentication if the service is ever exposed publicly.

Job metadata is still kept in memory. If you later scale to multiple Railway
replicas or need restart persistence, move JOBS to Redis/Postgres and place
video files on a Railway volume/object storage.
"""
import errno
import logging
import os
import queue
import re
import shutil
import tempfile
import threading
import time
import uuid
from pathlib import Path

from fastapi import FastAPI, UploadFile, File, Form, Header, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse

from . import drive, pipeline

app = FastAPI(title="SLC Video Merger API")
logger = logging.getLogger("slc-video-merger")

# ── CORS ──────────────────────────────────────────────────────────────────
# Set FRONTEND_ORIGIN on Railway to your Vercel URL, e.g.
# https://your-app.vercel.app  (comma-separate if you have more than one)
_origins_env = os.environ.get("FRONTEND_ORIGIN", "*")
ALLOWED_ORIGINS = [o.strip() for o in _origins_env.split(",")] if _origins_env != "*" else ["*"]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ── Resource limits ───────────────────────────────────────────────────────
MAX_UPLOAD_MB = max(1, int(os.environ.get("MAX_UPLOAD_MB", "500")))
UPLOAD_CHUNK_MB = max(1, int(os.environ.get("UPLOAD_CHUNK_MB", "1")))
UPLOAD_CHUNK_BYTES = UPLOAD_CHUNK_MB * 1024 * 1024
ALLOWED_VIDEO_EXTENSIONS = {".mp4", ".mov", ".webm", ".mkv", ".avi"}

# Global waiting queue protection. Processing jobs are not counted here;
# uploads in progress are counted as reservations so several users cannot all
# pass the limit at exactly the same moment.
MAX_QUEUED_JOBS = max(1, int(os.environ.get("MAX_QUEUED_JOBS", "20")))

# Fair-use protection for one browser/session. This counts that session's
# uploading + queued + processing jobs, so one user cannot monopolise the
# whole team queue. Finished jobs do not count against this number.
MAX_JOBS_PER_SESSION = max(1, int(os.environ.get("MAX_JOBS_PER_SESSION", "5")))

# Keep a minimum amount of disk unused and reserve extra temporary-space
# headroom for FFmpeg output/scratch while a queued upload waits. A factor of
# 2.5 means a 400 MB source is treated as needing roughly 1 GB of capacity
# across source + intermediates + output. Tune after observing real workloads.
MIN_FREE_DISK_MB = max(128, int(os.environ.get("MIN_FREE_DISK_MB", "1024")))
MIN_FREE_DISK_BYTES = MIN_FREE_DISK_MB * 1024 * 1024
DISK_HEADROOM_FACTOR = max(1.0, float(os.environ.get("DISK_HEADROOM_FACTOR", "2.5")))
DISK_CHECK_INTERVAL_BYTES = 32 * 1024 * 1024
UPLOAD_RESERVATION_TTL_SECONDS = max(60, int(os.environ.get("UPLOAD_RESERVATION_TTL_SECONDS", "3600")))

# Video encoding is CPU-bound. 1 is the safe Railway default; raise only after
# checking CPU/RAM metrics under realistic load.
WORKERS = max(1, int(os.environ.get("WORKERS", "1")))

# job_id -> job metadata. Private keys are prefixed with "_".
JOBS: dict[str, dict] = {}
JOBS_LOCK = threading.Lock()
JOB_QUEUE: "queue.Queue[str]" = queue.Queue()

# upload reservation token -> metadata. The frontend obtains a token from the
# lightweight /jobs/preflight endpoint before it starts the large multipart
# upload. This means queue/disk rejection can happen before video transfer.
UPLOAD_RESERVATIONS: dict[str, dict] = {}

WORK_ROOT = Path(tempfile.gettempdir()) / "slc-merger-jobs"
WORK_ROOT.mkdir(parents=True, exist_ok=True)

_SESSION_RE = re.compile(r"^[A-Za-z0-9_-]{16,128}$")


def _require_session_id(value: str | None) -> str:
    session_id = (value or "").strip()
    if not _SESSION_RE.fullmatch(session_id):
        raise HTTPException(400, "A valid browser session id is required. Refresh the page and try again.")
    return session_id


def _queued_count_locked() -> int:
    return sum(1 for job in JOBS.values() if job.get("status") == "queued")


def _processing_count_locked() -> int:
    return sum(1 for job in JOBS.values() if job.get("status") == "processing")


def _session_active_count_locked(session_id: str) -> int:
    jobs = sum(
        1
        for job in JOBS.values()
        if job.get("owner_session_id") == session_id and job.get("status") in ("queued", "processing")
    )
    uploads = sum(1 for item in UPLOAD_RESERVATIONS.values() if item.get("session_id") == session_id)
    return jobs + uploads


def _cleanup_expired_upload_reservations_locked() -> None:
    now = time.time()
    expired = [
        token
        for token, item in UPLOAD_RESERVATIONS.items()
        if item.get("state") == "reserved"
        and now - float(item.get("created_at", now)) > UPLOAD_RESERVATION_TTL_SECONDS
    ]
    for token in expired:
        UPLOAD_RESERVATIONS.pop(token, None)


def _reserved_headroom_bytes_locked() -> int:
    queued_or_processing = sum(
        int(job.get("_disk_headroom_bytes", 0) or 0)
        for job in JOBS.values()
        if job.get("status") in ("queued", "processing")
    )
    active_uploads = sum(int(item.get("reserve_bytes", 0) or 0) for item in UPLOAD_RESERVATIONS.values())
    return queued_or_processing + active_uploads


def _planned_upload_reservation_bytes(declared_size: int | None) -> int:
    expected_size = declared_size if declared_size and declared_size > 0 else MAX_UPLOAD_MB * 1024 * 1024
    return int(expected_size * DISK_HEADROOM_FACTOR)


def _reserve_upload(reservation_token: str, session_id: str, declared_size: int, filename: str) -> None:
    """Atomically reserve a waiting slot and conservative disk headroom."""
    with JOBS_LOCK:
        _cleanup_expired_upload_reservations_locked()
        queued = _queued_count_locked()
        if queued + len(UPLOAD_RESERVATIONS) >= MAX_QUEUED_JOBS:
            raise HTTPException(
                429,
                f"The team queue is full ({MAX_QUEUED_JOBS} waiting uploads). Please try again after a queued video starts processing.",
            )

        session_active = _session_active_count_locked(session_id)
        if session_active >= MAX_JOBS_PER_SESSION:
            raise HTTPException(
                429,
                f"This browser already has {session_active} active video job(s). The per-browser limit is {MAX_JOBS_PER_SESSION}.",
            )

        disk = shutil.disk_usage(WORK_ROOT)
        planned = _planned_upload_reservation_bytes(declared_size)
        already_reserved = _reserved_headroom_bytes_locked()
        projected_free = disk.free - already_reserved - planned
        if projected_free < MIN_FREE_DISK_BYTES:
            free_mb = max(0, (disk.free - already_reserved) // 1048576)
            raise HTTPException(
                507,
                f"The video server is low on safe working storage (about {free_mb} MB available after reservations). Please try again later.",
            )

        UPLOAD_RESERVATIONS[reservation_token] = {
            "session_id": session_id,
            "reserve_bytes": planned,
            "declared_size": declared_size,
            "filename": filename,
            "created_at": time.time(),
            "state": "reserved",
        }


def _claim_upload_reservation(reservation_token: str | None, session_id: str, declared_size: int | None, filename: str) -> str:
    token = (reservation_token or "").strip()
    if not token:
        raise HTTPException(428, "Upload preflight is required. Refresh the page and retry the upload.")
    with JOBS_LOCK:
        _cleanup_expired_upload_reservations_locked()
        item = UPLOAD_RESERVATIONS.get(token)
        if not item or item.get("session_id") != session_id or item.get("state") != "reserved":
            raise HTTPException(409, "Upload reservation is missing, expired or already used. Please retry the upload.")
        expected_size = int(item.get("declared_size", 0) or 0)
        if declared_size is not None and expected_size and declared_size != expected_size:
            raise HTTPException(409, "The selected file changed after upload preflight. Please retry.")
        if Path(filename).suffix.lower() != Path(str(item.get("filename", ""))).suffix.lower():
            raise HTTPException(409, "The selected file changed after upload preflight. Please retry.")
        item["state"] = "uploading"
    return token


def _release_upload_reservation(reservation_token: str) -> None:
    with JOBS_LOCK:
        UPLOAD_RESERVATIONS.pop(reservation_token, None)


def _queue_positions_locked() -> dict[str, int]:
    queued_ids = [jid for jid, job in JOBS.items() if job.get("status") == "queued"]
    queued_ids.sort(key=lambda jid: (JOBS[jid].get("created_at", 0), jid))
    return {jid: index + 1 for index, jid in enumerate(queued_ids)}


def _owned_job_locked(job_id: str, session_id: str) -> dict:
    job = JOBS.get(job_id)
    if not job or job.get("owner_session_id") != session_id:
        # Return 404 rather than 403 so one session cannot probe another
        # session's job ids.
        raise HTTPException(404, "Job not found")
    return job


def _worker_loop():
    while True:
        job_id = JOB_QUEUE.get()
        try:
            _run_job(job_id)
        finally:
            JOB_QUEUE.task_done()


def _run_job(job_id: str):
    with JOBS_LOCK:
        job = JOBS.get(job_id)
        if not job:
            return
        job["status"] = "processing"
        course_name, unit_number, chapter_number, awarding_body, input_path = (
            job["course_name"], job["unit_number"], job.get("chapter_number", ""),
            job.get("awarding_body", ""), Path(job.pop("_input_path")),
        )

    def progress_cb(msg: str):
        with JOBS_LOCK:
            if job_id in JOBS:
                JOBS[job_id]["progress"].append(msg)

    job_dir = WORK_ROOT / job_id
    scratch = job_dir / "scratch"
    scratch.mkdir(parents=True, exist_ok=True)

    try:
        final_path, filename = pipeline.process_video(
            course_name, unit_number, input_path, scratch, progress_cb=progress_cb,
            chapter_number=chapter_number, awarding_body=awarding_body,
        )
        out_path = job_dir / filename
        if out_path.exists():
            out_path.unlink()
        # Keep the completed MP4 on disk. Do not read it back into Python RAM.
        shutil.move(str(final_path), str(out_path))
        with JOBS_LOCK:
            if job_id in JOBS:
                JOBS[job_id]["status"] = "done"
                JOBS[job_id]["result_path"] = str(out_path)
                JOBS[job_id]["result_filename"] = filename
    except Exception as e:
        logger.exception("Video processing failed for job %s", job_id)
        with JOBS_LOCK:
            if job_id in JOBS:
                JOBS[job_id]["status"] = "failed"
                JOBS[job_id]["error"] = pipeline._sanitise_error(e)
    finally:
        try:
            input_path.unlink(missing_ok=True)
        except Exception:
            pass
        shutil.rmtree(scratch, ignore_errors=True)
        # Processing headroom no longer needs to be reserved. The actual final
        # file still consumes real disk and is therefore naturally reflected
        # by shutil.disk_usage() for later upload checks.
        with JOBS_LOCK:
            if job_id in JOBS:
                JOBS[job_id]["_disk_headroom_bytes"] = 0


@app.on_event("startup")
def _startup():
    pipeline.ensure_assets()

    # JOBS is in-memory. After a restart there is no metadata that can safely
    # reconnect old /tmp files to queue items, so remove orphaned work dirs.
    for child in WORK_ROOT.iterdir():
        if child.is_dir():
            shutil.rmtree(child, ignore_errors=True)
        else:
            try:
                child.unlink()
            except OSError:
                pass

    logger.info(
        "Starting video merger: workers=%s prep_workers=%s max_upload_mb=%s max_queued=%s per_session=%s min_free_disk_mb=%s disk_factor=%s",
        WORKERS,
        pipeline.PIPELINE_PREP_WORKERS,
        MAX_UPLOAD_MB,
        MAX_QUEUED_JOBS,
        MAX_JOBS_PER_SESSION,
        MIN_FREE_DISK_MB,
        DISK_HEADROOM_FACTOR,
    )
    for _ in range(WORKERS):
        threading.Thread(target=_worker_loop, daemon=True).start()


@app.get("/healthz")
def healthz():
    disk = shutil.disk_usage(WORK_ROOT)
    with JOBS_LOCK:
        _cleanup_expired_upload_reservations_locked()
        queued = _queued_count_locked()
        processing = _processing_count_locked()
        uploading = len(UPLOAD_RESERVATIONS)
        reserved_mb = _reserved_headroom_bytes_locked() // 1048576
    return {
        "ok": True,
        "workers": WORKERS,
        "queue_depth": queued,
        "processing": processing,
        "uploading": uploading,
        "max_queued_jobs": MAX_QUEUED_JOBS,
        "max_jobs_per_session": MAX_JOBS_PER_SESSION,
        "max_upload_mb": MAX_UPLOAD_MB,
        "upload_chunk_mb": UPLOAD_CHUNK_MB,
        "pipeline_prep_workers": pipeline.PIPELINE_PREP_WORKERS,
        "work_disk_free_mb": disk.free // 1048576,
        "reserved_headroom_mb": reserved_mb,
        "min_free_disk_mb": MIN_FREE_DISK_MB,
        "disk_headroom_factor": DISK_HEADROOM_FACTOR,
        "upload_reservation_ttl_seconds": UPLOAD_RESERVATION_TTL_SECONDS,
        "drive_auth_mode": drive.auth_mode(),
        "drive_root_folder_id": drive._root_folder_id(),
    }


@app.post("/jobs/preflight")
def preflight_upload(
    file_size: int = Query(..., ge=1),
    filename: str = Query(..., min_length=1),
    x_session_id: str | None = Header(default=None, alias="X-Session-Id"),
):
    session_id = _require_session_id(x_session_id)
    suffix = Path(filename).suffix.lower()
    if suffix not in ALLOWED_VIDEO_EXTENSIONS:
        raise HTTPException(415, "Unsupported video type. Use MP4, MOV, WebM, MKV or AVI.")
    max_bytes = MAX_UPLOAD_MB * 1024 * 1024
    if file_size > max_bytes:
        size_mb = file_size / 1048576
        raise HTTPException(413, f"File too large ({size_mb:.0f} MB). Limit is {MAX_UPLOAD_MB} MB.")

    token = uuid.uuid4().hex
    _reserve_upload(token, session_id, file_size, filename)
    return {
        "reservation_token": token,
        "expires_in_seconds": UPLOAD_RESERVATION_TTL_SECONDS,
    }


@app.delete("/jobs/preflight/{reservation_token}")
def cancel_preflight(
    reservation_token: str,
    x_session_id: str | None = Header(default=None, alias="X-Session-Id"),
):
    session_id = _require_session_id(x_session_id)
    with JOBS_LOCK:
        item = UPLOAD_RESERVATIONS.get(reservation_token)
        if not item or item.get("session_id") != session_id:
            raise HTTPException(404, "Upload reservation not found")
        if item.get("state") == "uploading":
            raise HTTPException(409, "Upload is already being accepted")
        UPLOAD_RESERVATIONS.pop(reservation_token, None)
    return {"cancelled": True}


@app.post("/jobs")
async def create_job(
    course_name: str = Form(...),
    unit_number: str = Form(...),
    chapter_number: str = Form(""),
    awarding_body: str = Form(""),
    video: UploadFile = File(...),
    x_session_id: str | None = Header(default=None, alias="X-Session-Id"),
    x_upload_reservation: str | None = Header(default=None, alias="X-Upload-Reservation"),
):
    session_id = _require_session_id(x_session_id)

    if not video.filename:
        await video.close()
        raise HTTPException(400, "No file uploaded")

    suffix = Path(video.filename).suffix.lower()
    if suffix not in ALLOWED_VIDEO_EXTENSIONS:
        await video.close()
        raise HTTPException(415, "Unsupported video type. Use MP4, MOV, WebM, MKV or AVI.")

    max_bytes = MAX_UPLOAD_MB * 1024 * 1024
    declared_size = getattr(video, "size", None)
    if declared_size is not None and declared_size > max_bytes:
        await video.close()
        size_mb = declared_size / 1048576
        raise HTTPException(413, f"File too large ({size_mb:.0f} MB). Limit is {MAX_UPLOAD_MB} MB.")

    try:
        reservation_token = _claim_upload_reservation(
            x_upload_reservation, session_id, declared_size, video.filename
        )
    except HTTPException:
        await video.close()
        raise

    job_id = uuid.uuid4().hex[:12]
    reservation_active = True
    job_dir = WORK_ROOT / job_id
    input_path = job_dir / f"input{suffix}"
    total_bytes = 0
    last_disk_check = 0

    try:
        job_dir.mkdir(parents=True, exist_ok=False)
        with input_path.open("wb") as dest:
            while True:
                chunk = await video.read(UPLOAD_CHUNK_BYTES)
                if not chunk:
                    break
                total_bytes += len(chunk)
                if total_bytes > max_bytes:
                    size_mb = total_bytes / 1048576
                    raise HTTPException(
                        413,
                        f"File too large ({size_mb:.0f} MB read). Limit is {MAX_UPLOAD_MB} MB.",
                    )
                dest.write(chunk)

                # Existing FFmpeg work can grow while this upload is arriving.
                # Abort before the filesystem reaches a critically low level.
                if total_bytes - last_disk_check >= DISK_CHECK_INTERVAL_BYTES:
                    last_disk_check = total_bytes
                    if shutil.disk_usage(WORK_ROOT).free < MIN_FREE_DISK_BYTES:
                        raise HTTPException(
                            507,
                            f"The video server reached its {MIN_FREE_DISK_MB} MB storage safety reserve during upload. Please try again later.",
                        )

        if total_bytes == 0:
            raise HTTPException(400, "Uploaded video is empty")

        extra_headroom = int(total_bytes * max(0.0, DISK_HEADROOM_FACTOR - 1.0))
        with JOBS_LOCK:
            UPLOAD_RESERVATIONS.pop(reservation_token, None)
            reservation_active = False
            JOBS[job_id] = {
                "status": "queued",
                "progress": [],
                "error": None,
                "result_path": None,
                "result_filename": None,
                "course_name": course_name,
                "unit_number": unit_number,
                "chapter_number": chapter_number,
                "awarding_body": awarding_body,
                "original_filename": video.filename,
                "created_at": time.time(),
                "upload_size_bytes": total_bytes,
                "owner_session_id": session_id,
                "_input_path": str(input_path),
                "_disk_headroom_bytes": extra_headroom,
                "drive_status": "idle",  # idle | saving | saved | failed
                "drive_error": None,
                "drive_link": None,
            }

        JOB_QUEUE.put(job_id)
        return {"job_id": job_id}

    except HTTPException:
        shutil.rmtree(job_dir, ignore_errors=True)
        raise
    except OSError as e:
        shutil.rmtree(job_dir, ignore_errors=True)
        if e.errno == errno.ENOSPC:
            logger.exception("Upload failed because work disk is full")
            raise HTTPException(507, "The video server is temporarily low on storage. Please try again later.") from e
        logger.exception("Could not store uploaded video")
        raise HTTPException(500, "The server could not store the uploaded video. Please retry.") from e
    except Exception as e:
        shutil.rmtree(job_dir, ignore_errors=True)
        logger.exception("Could not store uploaded video")
        raise HTTPException(500, "The server could not store the uploaded video. Please retry.") from e
    finally:
        if reservation_active:
            _release_upload_reservation(reservation_token)
        await video.close()


def _public_job(job_id: str, job: dict, queue_position: int | None = None) -> dict:
    return {
        "job_id": job_id,
        "status": job["status"],
        "queue_position": queue_position if job.get("status") == "queued" else None,
        "progress": job["progress"][-20:],
        "error": job["error"],
        "result_filename": job["result_filename"],
        "original_filename": job["original_filename"],
        "course_name": job["course_name"],
        "unit_number": job["unit_number"],
        "chapter_number": job.get("chapter_number", ""),
        "awarding_body": job.get("awarding_body", ""),
        "created_at": job["created_at"],
        "drive_status": job.get("drive_status", "idle"),
        "drive_error": job.get("drive_error"),
        "drive_link": job.get("drive_link"),
    }


@app.get("/jobs")
def list_jobs(x_session_id: str | None = Header(default=None, alias="X-Session-Id")):
    session_id = _require_session_id(x_session_id)
    with JOBS_LOCK:
        _cleanup_expired_upload_reservations_locked()
        positions = _queue_positions_locked()
        jobs = [
            _public_job(jid, job, positions.get(jid))
            for jid, job in JOBS.items()
            if job.get("owner_session_id") == session_id
        ]
        queue_info = {
            "queued": _queued_count_locked(),
            "processing": _processing_count_locked(),
            "uploading": len(UPLOAD_RESERVATIONS),
            "capacity": MAX_QUEUED_JOBS,
            "session_active": _session_active_count_locked(session_id),
            "session_limit": MAX_JOBS_PER_SESSION,
        }
    jobs.sort(key=lambda item: item["created_at"], reverse=True)
    return {"jobs": jobs, "queue": queue_info}


@app.get("/jobs/{job_id}")
def get_job(job_id: str, x_session_id: str | None = Header(default=None, alias="X-Session-Id")):
    session_id = _require_session_id(x_session_id)
    with JOBS_LOCK:
        job = _owned_job_locked(job_id, session_id)
        position = _queue_positions_locked().get(job_id)
        return _public_job(job_id, job, position)


@app.get("/jobs/{job_id}/file")
def get_job_file(
    job_id: str,
    session_id: str | None = Query(default=None),
    x_session_id: str | None = Header(default=None, alias="X-Session-Id"),
):
    owner_session_id = _require_session_id(x_session_id or session_id)
    with JOBS_LOCK:
        job = _owned_job_locked(job_id, owner_session_id)
        if job["status"] != "done" or not job["result_path"]:
            raise HTTPException(409, f"Job is not finished (status: {job['status']})")
        path = job["result_path"]
        filename = job["result_filename"]

    return FileResponse(path, media_type="video/mp4", filename=filename)


def _run_drive_save(job_id: str):
    with JOBS_LOCK:
        job = JOBS.get(job_id)
        if not job:
            return
        course_name = job["course_name"]
        unit_number = job["unit_number"]
        chapter_number = job.get("chapter_number", "")
        awarding_body = job.get("awarding_body", "")
        result_path = job["result_path"]

    try:
        result = drive.upload_video(
            course_name, unit_number, chapter_number, result_path,
            awarding_body=awarding_body,
        )
        with JOBS_LOCK:
            if job_id in JOBS:
                JOBS[job_id]["drive_status"] = "saved"
                JOBS[job_id]["drive_link"] = result["web_view_link"]
                JOBS[job_id]["drive_error"] = None
    except Exception as e:
        with JOBS_LOCK:
            if job_id in JOBS:
                JOBS[job_id]["drive_status"] = "failed"
                JOBS[job_id]["drive_error"] = pipeline._sanitise_error(e)


@app.post("/jobs/{job_id}/drive")
def save_to_drive(
    job_id: str,
    x_session_id: str | None = Header(default=None, alias="X-Session-Id"),
):
    session_id = _require_session_id(x_session_id)
    with JOBS_LOCK:
        job = _owned_job_locked(job_id, session_id)
        if job["status"] != "done" or not job["result_path"]:
            raise HTTPException(409, f"Job is not finished (status: {job['status']})")
        if job.get("drive_status") == "saving":
            raise HTTPException(409, "Already saving to Drive")
        job["drive_status"] = "saving"
        job["drive_error"] = None

    threading.Thread(target=_run_drive_save, args=(job_id,), daemon=True).start()
    return {"drive_status": "saving"}


@app.delete("/jobs/{job_id}")
def delete_job(
    job_id: str,
    x_session_id: str | None = Header(default=None, alias="X-Session-Id"),
):
    """Remove only a finished/failed job owned by the requesting session."""
    session_id = _require_session_id(x_session_id)
    with JOBS_LOCK:
        job = _owned_job_locked(job_id, session_id)
        if job["status"] in ("queued", "processing"):
            raise HTTPException(409, "Can't remove a job that hasn't finished yet")
        del JOBS[job_id]

    shutil.rmtree(WORK_ROOT / job_id, ignore_errors=True)
    return {"deleted": True}
